#!/usr/bin/env bash
# Writes ios/Version.xcconfig from ios/VERSION (the iOS app's own version, X.Y.Z; bump it with
# scripts/release.sh ios X.Y.Z). Build number = major*1000000 + minor*1000 + patch
# (0.3.3 -> 3003), the same scheme as Android's versionCode (Shared/AppVersion.swift).
# Run by xcodegen (preGenCommand) before it generates the project.
set -euo pipefail
cd "$(dirname "$0")/.."
version="$(tr -d '[:space:]' < VERSION)"
if ! [[ "$version" =~ ^([0-9]+)\.([0-9]+)\.([0-9]+)$ ]]; then
  echo "version.sh: ios/VERSION must be X.Y.Z (got '$version')" >&2
  exit 1
fi
major=${BASH_REMATCH[1]} minor=$((10#${BASH_REMATCH[2]})) patch=$((10#${BASH_REMATCH[3]}))
if (( minor >= 1000 || patch >= 1000 )); then echo "version.sh: minor and patch must be below 1000" >&2; exit 1; fi
build=$(( 10#$major * 1000000 + minor * 1000 + patch ))
cat > Version.xcconfig <<XC
// Generated by scripts/version.sh from ios/VERSION. Do not edit.
MARKETING_VERSION = $version
CURRENT_PROJECT_VERSION = $build
// Optional, not committed: local overrides (e.g. another DEVELOPMENT_TEAM).
#include? "Local.xcconfig"
XC
echo "PassAuth iOS version $version ($build)"
