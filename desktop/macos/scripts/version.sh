#!/usr/bin/env bash
# Writes desktop/macos/Version.xcconfig from desktop/package.json: the AutoFill extension
# ships inside the desktop app, so it carries the desktop app's version. Build number =
# major*1000000 + minor*1000 + patch, as for iOS and Android. Run by xcodegen (preGenCommand).
set -euo pipefail
cd "$(dirname "$0")/.."
version="$(sed -n 's/^[[:space:]]*"version":[[:space:]]*"\([^"]*\)".*/\1/p' ../package.json | head -1)"
if ! [[ "$version" =~ ^([0-9]+)\.([0-9]+)\.([0-9]+)$ ]]; then
  echo "version.sh: desktop/package.json version must be X.Y.Z (got '$version')" >&2
  exit 1
fi
major=${BASH_REMATCH[1]} minor=$((10#${BASH_REMATCH[2]})) patch=$((10#${BASH_REMATCH[3]}))
build=$(( 10#$major * 1000000 + minor * 1000 + patch ))
cat > Version.xcconfig <<XC
// Generated by scripts/version.sh from desktop/package.json. Do not edit.
MARKETING_VERSION = $version
CURRENT_PROJECT_VERSION = $build
XC
echo "PassAuth AutoFill (macOS) version $version ($build)"
